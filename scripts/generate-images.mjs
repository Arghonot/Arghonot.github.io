import { readdir, mkdir, stat, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const magick = process.env.IMAGEMAGICK_BINARY || 'magick';
const manifest = {};
let generated = 0, sourceBytes = 0, thumbnailBytes = 0;
async function walk(dir) {
  for (const entry of await readdir(path.join(root, dir), { withFileTypes: true })) {
    const src = `${dir}/${entry.name}`;
    if (entry.isDirectory()) { await walk(src); continue; }
    if (!/\.(png|jpe?g|webp)$/i.test(src) || entry.name.startsWith('_')) continue;
    const input = path.join(root, src);
    const sourceStat = await stat(input);
    const metadata = spawnSync(magick, ['identify', '-format', '%w %h', `${input}[0]`], { encoding: 'utf8' });
    if (metadata.status !== 0) throw new Error(metadata.stderr || 'ImageMagick is required. Install it or set IMAGEMAGICK_BINARY.');
    const [width, height] = metadata.stdout.trim().split(/\s+/).map(Number);
    const variants = [];
    for (const size of [...new Set([Math.min(320, width), Math.min(640, width), Math.min(1280, width)])]) {
      const output = `assets/optimized/${src.slice(7)}.${size}.webp`;
      const target = path.join(root, output);
      await mkdir(path.dirname(target), { recursive: true });
      const existing = await stat(target).catch(() => null);
      if (!existing || existing.mtimeMs < sourceStat.mtimeMs) {
        const result = spawnSync(magick, [`${input}[0]`, '-auto-orient', '-resize', `${size}x>`, '-strip', '-quality', '82', target], { encoding: 'utf8' });
        if (result.status !== 0) throw new Error(result.stderr);
        generated++;
      }
      variants.push({ src: output, width: size });
    }
    manifest[src] = { width, height, variants };
    sourceBytes += sourceStat.size;
    thumbnailBytes += (await stat(path.join(root, variants[0].src))).size;
  }
}
for (const dir of ['assets/projects', 'assets/work', 'assets/hof']) await walk(dir);
const output = `/* Generated by npm run images. */\nwindow.IMAGE_VARIANTS = ${JSON.stringify(manifest)};\n`;
const manifestPath = path.join(root, 'app/image-variants.js');
if (await readFile(manifestPath, 'utf8').catch(() => '') !== output) await writeFile(manifestPath, output);
console.log(`${Object.keys(manifest).length} images; ${generated} variants generated. Originals ${(sourceBytes / 1e6).toFixed(2)} MB; smallest variants ${(thumbnailBytes / 1e6).toFixed(2)} MB.`);
